func TestNaming(t *testing.T) {
	n := Naming{Name: "kama_x"}
	assert.Equal(t, n.Suffix(), ".kama_x")
	assert.Equal(t, n.SharedFile("helper"), "zz_gen.helper.kama_x.go")

	for _, c := range []struct{ src, file, shared string }{
		{"d/a.go", "d/a.kama_x.go", "d/zz_gen.helper.a.kama_x.go"},
		{"d/a_linux.go", "d/a.kama_x_linux.go", "d/zz_gen.helper.a.kama_x_linux.go"},
		{
			"d/a_linux_amd64.go",
			"d/a.kama_x_linux_amd64.go",
			"d/zz_gen.helper.a.kama_x_linux_amd64.go",
		},
		{"d/a_tagged.go", "d/a_tagged.kama_x.go", "d/zz_gen.helper.a_tagged.kama_x.go"},
	} {
		assert.Equal(t, n.SourceFile(c.src), filepath.FromSlash(c.file))
		assert.Equal(t, n.SharedFileOf("helper", c.src), filepath.FromSlash(c.shared))
		assert.Assert(t, n.IsShared("helper", path.Base(c.shared)), c.shared)
		assert.Assert(t, !n.IsShared("helper", path.Base(c.file)), c.file)
		assert.Assert(t, !n.IsShared("flagset", path.Base(c.shared)), c.shared)
	}
	assert.Assert(t, n.IsShared("helper", n.SharedFile("helper")))
	assert.Assert(t, !n.IsShared("helper", "zz_gen.helper.kama_y.go"))

	assert.Assert(t, !Constrained("d/a.go"))
	assert.Assert(t, !Constrained("d/a_tagged.go"))
	assert.Assert(t, Constrained("d/a_linux.go"))
	assert.Assert(t, Constrained("d/a_amd64.go"))
}

func TestHostShared(t *testing.T) {
	uses := func(names ...string) map[string]bool {
		m := map[string]bool{}
		for _, n := range names {
			m[n] = true
		}
		return m
	}
	hosts := HostShared("shared.go", []Caller{
		{Uses: uses("everywhere", "both")},
		{
			Constrained: true,
			BuildLine:   "//go:build a",
			Own:         "a.go",
			Uses:        uses("both", "onlyA", "ab"),
		},
		{Constrained: true, BuildLine: "//go:build b", Own: "b.go", Uses: uses("ab", "onlyB")},
		{Uses: nil},
	})
	assert.DeepEqual(t, hosts, []Host{
		// A name constrained callers share goes to the first of them.
		{Path: "a.go", BuildLine: "//go:build a", Names: []string{"ab", "onlyA"}},
		{Path: "b.go", BuildLine: "//go:build b", Names: []string{"onlyB"}},
		{Path: "shared.go", Names: []string{"both", "everywhere"}},
	})
	assert.Equal(t, len(HostShared("shared.go", nil)), 0)
}

func TestRelFiles(t *testing.T) {
	root := t.TempDir()
	files, err := RelFiles(root, []File{
		{Path: filepath.Join(root, "a", "b.go"), Content: []byte("x")},
	})
	assert.NilError(t, err)
	assert.DeepEqual(t, files, []File{{Path: "a/b.go", Content: []byte("x")}})

	_, err = RelFiles(root, []File{{Path: filepath.Join(filepath.Dir(root), "b.go")}})
	assert.ErrorContains(t, err, "is outside")
}

type recordReporter struct {
	warnings []error
	progress []string
}

func (r *recordReporter) Warn(w error)        { r.warnings = append(r.warnings, w) }
func (r *recordReporter) Progress(msg string) { r.progress = append(r.progress, msg) }

// source returns a generated file of package p with the header of now.
func source(t *testing.T, now time.Time, body string) []byte {
	t.Helper()
	hdr, err := Header("example.com/gen", map[string]any{"mode": "x"}, now)
	assert.NilError(t, err)
	return []byte(strings.Join(hdr, "\n") + "\n\npackage p\n\n" + body + "\n")
}

func TestHeader(t *testing.T) {
	hdr, err := Header(
		"example.com/gen",
		map[string]any{"b": 1, "a": "x"},
		time.Date(2026, 11, 4, 19, 12, 33, 5, time.FixedZone("", 9*60*60)),
	)
	assert.NilError(t, err)
	assert.DeepEqual(t, hdr, []string{
		"// Code generated by example.com/gen. DO NOT EDIT.",
		"// params:",
		"//\ta: \"x\"",
		"//\tb: 1",
		"// generated: 2026-11-04T10:12:33Z",
	})
}

func TestStage(t *testing.T) {
	ctx := context.Background()
	f, err := overlayfs.New(t.TempDir())
	assert.NilError(t, err)
	defer f.Close()

	first := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
	files := func(now time.Time, a string) []File {
		return []File{
			{Path: "a.go", Content: source(t, now, a)},
			{Path: "sub/b.go", Content: source(t, now, "var B = 1")},
		}
	}
	read := func(name string) string {
		b, err := fs.ReadFile(f.FS(), name)
		assert.NilError(t, err)
		return string(b)
	}

	r := &recordReporter{}
	assert.NilError(t, Stage(ctx, f, files(first, "var A = 1"), r))
	assert.DeepEqual(t, r.progress, []string{"2 files written, 0 files unchanged"})
	a, b := read("a.go"), read("sub/b.go")

	// A later run changing nothing but the time keeps both files.
	r = &recordReporter{}
	assert.NilError(t, Stage(ctx, f, files(first.Add(time.Hour), "var A = 1"), r))
	assert.DeepEqual(t, r.progress, []string{"0 files written, 2 files unchanged"})
	assert.Equal(t, read("a.go"), a)

	r = &recordReporter{}
	assert.NilError(t, Stage(ctx, f, files(first.Add(time.Hour), "var A = 2"), r))
	assert.DeepEqual(t, r.progress, []string{"1 file written, 1 file unchanged"})
	assert.Assert(t, strings.Contains(read("a.go"), "var A = 2"))
	assert.Assert(t, strings.Contains(read("a.go"), "generated: 2026-01-01T01:00:00Z"))
	assert.Equal(t, read("sub/b.go"), b)
}

type fakeParam struct {
	Name string `json:"name"`
}

var errFakeParam = errors.New("fake: name is required")

// fakeGenerator writes one file named by its param and warns once.
type fakeGenerator struct{ name string }

func (g *fakeGenerator) Configure(p fakeParam) error {
	if p.Name == "" {
		return errFakeParam
	}
	g.name = p.Name
	return nil
}

func (g *fakeGenerator) Generate(
	_ context.Context,
	in *overlayfs.Fs,
	out *overlayfs.Fs,
) ([]File, []error, error) {
	if in != out {
		return nil, nil, errors.New("fake: in is not out")
	}
	return []File{{Path: g.name + ".go", Content: []byte("package p\n")}},
		[]error{errors.New("fake warning")},
		nil
}

func newFakeGenerator() Generator[fakeParam, *overlayfs.Fs] { return &fakeGenerator{} }

func init() { workflow.Register("base_test.fake", NewProc(newFakeGenerator)) }

// TestProc runs a Generator as a step of a workflow graph, whose formation
// checks the methods of the instance against the types the proc declares.
func TestProc(t *testing.T) {
	ctx := context.Background()
	root := t.TempDir()
	spec := func(param any) workflow.Spec {
		return workflow.Spec{Version: 1, Steps: map[string]workflow.Step{
			"root": {Proc: "overlayfs.open", Param: map[string]any{"root": root}},
			"gen": {
				Proc:  "base_test.fake",
				In:    workflow.Names{"root"},
				Out:   workflow.Names{"root"},
				Param: param,
			},
			"final": {
				Proc:  "overlayfs.copy_down",
				In:    workflow.Names{"root"},
				After: workflow.Names{"gen"},
			},
		}}
	}

	_, err := spec(map[string]any{}).Build(ctx, workflow.DefaultRegistry)
	assert.ErrorIs(t, err, errFakeParam)

	g, err := spec(map[string]any{"name": "made"}).Build(ctx, workflow.DefaultRegistry)
	assert.NilError(t, err)
	r := &recordReporter{}
	assert.NilError(t, g.Run(ctx, workflow.ProgressControl{
		OnWarning:  func(_ string, w error) { r.Warn(w) },
		OnProgress: func(_ string, msg string) { r.Progress(msg) },
	}))
	assert.Equal(t, len(r.warnings), 1, "%v", r.warnings)
	assert.ErrorContains(t, r.warnings[0], "fake warning")
	assert.Assert(
		t,
		slices.Contains(r.progress, "1 file written, 0 files unchanged"),
		"%v",
		r.progress,
	)

	f, err := overlayfs.New(root)
	assert.NilError(t, err)
	defer f.Close()
	b, err := fs.ReadFile(f.FS(), "made.go")
	assert.NilError(t, err)
	assert.Equal(t, string(b), "package p\n")
}

// load stages files under the inline test directory of t and loads their
// packages.
func load(t *testing.T, files map[string]string, buildFlags ...string) []*packages.Package {
	t.Helper()

	f, err := overlayfs.New(".")
	assert.NilError(t, err)
	t.Cleanup(func() { f.Close() })

	dir := "testdata/inline/" + strings.NewReplacer("/", "_", " ", "_").Replace(t.Name())
	dirs := map[string]bool{}
	for name, src := range files {
		assert.NilError(t, f.Write(context.Background(), path.Join(dir, name), []byte(src)))
		dirs["./"+path.Dir(path.Join(dir, name))] = true
	}
	pkgs, err := gopackages.Load(context.Background(), f, gopackages.Options{
		Patterns:   slices.Sorted(maps.Keys(dirs)),
		BuildFlags: buildFlags,
		Tests:      true,
	})
	assert.NilError(t, err)
	return pkgs
}

func fileOf(t *testing.T, pkgs []*packages.Package, name string) (*packages.Package, *ast.File) {
	t.Helper()
	for _, pkg := range pkgs {
		for _, f := range pkg.Syntax {
			if filepath.Base(pkg.Fset.File(f.Pos()).Name()) == name {
				return pkg, f
			}
		}
	}
	t.Fatalf("no file %s", name)
	return nil, nil
}

func TestSourcePackages(t *testing.T) {
	pkgs := load(t, map[string]string{
		"a.go":      "package x\n\ntype A int\n",
		"a_test.go": "package x\n\nimport \"testing\"\n\nfunc TestA(*testing.T) {}\n",
	})
	isTestVariant := func(p *packages.Package) bool { return p.ID != p.PkgPath }
	assert.Assert(t, slices.ContainsFunc(pkgs, isTestVariant), "a test variant is loaded")
	src := SourcePackages(pkgs)
	assert.Assert(t, !slices.ContainsFunc(src, isTestVariant))
	paths := slices.Collect(opiter.Map(pkgPathOf, slices.Values(src)))
	assert.DeepEqual(t, paths, slices.Compact(slices.Clone(paths)))
	assert.Assert(t, slices.Contains(paths, pkgs[0].PkgPath))
}

func TestBuildConstraint(t *testing.T) {
	pkgs := load(t, map[string]string{
		"a.go": "// Package x.\npackage x\n\ntype A int\n",
		"b.go": "// Copyright.\n\n//go:build tagged || !tagged\n\n// Package x.\npackage x\n",
	})
	_, a := fileOf(t, pkgs, "a.go")
	_, ok := BuildConstraint(a)
	assert.Assert(t, !ok)
	_, b := fileOf(t, pkgs, "b.go")
	line, ok := BuildConstraint(b)
	assert.Assert(t, ok)
	assert.Equal(t, line, "//go:build tagged || !tagged")
}

func TestShadowedPredeclared(t *testing.T) {
	pkgs := SourcePackages(load(t, map[string]string{
		"a.go": "package x\n\ntype string int\n\ntype error int\n\ntype other int\n",
	}))
	names := func(contents ...string) []string {
		t.Helper()
		in := slices.Collect(opiter.Map(toBytes, slices.Values(contents)))
		objs, err := ShadowedPredeclared(pkgs[0], in)
		assert.NilError(t, err)
		return slices.Collect(opiter.Map(objectName, slices.Values(objs)))
	}
	assert.DeepEqual(t, names("package x\n\nvar V string\n\nfunc f() error { return nil }\n"),
		[]string{"error", "string"})
	// Selected names, fields and declared names are not uses.
	assert.Equal(t, len(names(
		"package x\n\nimport \"y\"\n\ntype T struct{ string int }\n\nvar V = y.error\n",
	)), 0)
	_, err := ShadowedPredeclared(pkgs[0], [][]byte{[]byte("not go")})
	assert.ErrorContains(t, err, "parse generated file")
}

func toBytes(s string) []byte { return []byte(s) }

func objectName(o types.Object) string { return o.Name() }

func TestStaleCheck(t *testing.T) {
	const gen = "base-test-gen"
	reg := genmark.NewRegistry()
	assert.NilError(t, reg.Register(gen))
	assert.NilError(t, reg.Register("other-gen"))

	marked := func(generator, name string) string {
		return "package x\n\n//kama:generated " + generator + "\ntype " + name + " int\n"
	}
	pkgs := SourcePackages(load(t, map[string]string{
		"a.go":       "package x\n\ntype A int\n",
		"made.go":    marked(gen, "Made"),
		"stale.go":   marked(gen, "Stale"),
		"kept.go":    marked(gen, "Kept"),
		"foreign.go": marked("other-gen", "Foreign"),
	}))
	pkg, made := fileOf(t, pkgs, "made.go")
	produced := []File{{Path: pkg.Fset.File(made.Pos()).Name()}}

	check := StaleCheck{Registry: reg, Generator: gen}
	warnings := check.Files(pkgs, produced)
	assert.Equal(t, len(warnings), 2, "%v", warnings)
	assert.ErrorIs(t, warnings[0], ErrStale)
	assert.ErrorContains(t, warnings[0], "/kept.go was generated by "+gen)
	assert.ErrorContains(t, warnings[1], "/stale.go was generated by "+gen)
	// The path is relative to the module root.
	assert.Assert(
		t,
		strings.Contains(warnings[1].Error(), ": generator/base/testdata/"),
		warnings[1],
	)

	check.Keep = func(_ *packages.Package, p string) bool { return filepath.Base(p) == "kept.go" }
	warnings = check.Files(pkgs, produced)
	assert.Equal(t, len(warnings), 1, "%v", warnings)
	assert.ErrorContains(t, warnings[0], "/stale.go")
}

func TestStaleCheckDir(t *testing.T) {
	const gen = "base-test-dir-gen"
	reg := genmark.NewRegistry()
	assert.NilError(t, reg.Register(gen))
	assert.NilError(t, reg.Register("other-gen"))

	ctx := context.Background()
	f, err := overlayfs.New(t.TempDir())
	assert.NilError(t, err)
	defer f.Close()
	marked := func(generator, name string) []byte {
		return []byte("package x\n\n//kama:generated " + generator + "\ntype " + name + " int\n")
	}
	for name, src := range map[string][]byte{
		"out/hand.go":      []byte("package x\n\ntype Hand int\n"),
		"out/made.go":      marked(gen, "Made"),
		"out/stale.go":     marked(gen, "Stale"),
		"out/foreign.go":   marked("other-gen", "Foreign"),
		"out/sub/below.go": marked(gen, "Below"),
		"elsewhere/x.go":   marked(gen, "Elsewhere"),
	} {
		assert.NilError(t, f.Write(ctx, name, src))
	}

	check := StaleCheck{Registry: reg, Generator: gen}
	warnings, err := check.Dir(f.FS(), "out", []File{{Path: "out/made.go"}})
	assert.NilError(t, err)
	assert.Equal(t, len(warnings), 1, "%v", warnings)
	assert.ErrorIs(t, warnings[0], ErrStale)
	assert.ErrorContains(t, warnings[0], "out/stale.go was generated by "+gen)

	// A directory not yet there holds no stale file.
	warnings, err = check.Dir(f.FS(), "missing", nil)
	assert.NilError(t, err)
	assert.Equal(t, len(warnings), 0)
}
