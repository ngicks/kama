package base

import (
	"cmp"
	"errors"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"path"
	"path/filepath"
	"slices"
	"strings"

	"github.com/ngicks/opiter"
	"golang.org/x/tools/go/packages"

	"github.com/ngicks/kama/kamalib/pkg/genmark"
)

// ErrStale reports a file of a loaded package that carries the marker of a
// generator and that the run of the generator did not produce.
var ErrStale = errors.New("generator: stale generated file")

// StaleCheck finds the files a generator wrote earlier and no longer
// produces.
type StaleCheck struct {
	// Registry tells the generator a marker names.
	Registry *genmark.Registry
	// Generator is the name the generator marks its declarations with.
	Generator string
	// Keep reports whether the file at path of pkg is left out although the
	// run did not produce it. Nil keeps none.
	Keep func(pkg *packages.Package, path string) bool
}

// Files returns a warning wrapping ErrStale for each file of pkgs holding a
// declaration marked by the generator that is not among produced, whose
// paths are absolute, sorted by path. A warning names the path relative to
// the module root where it lies under it.
func (c StaleCheck) Files(pkgs []*packages.Package, produced []File) []error {
	made := map[string]bool{}
	for _, f := range produced {
		made[filepath.Clean(f.Path)] = true
	}

	type stale struct{ path, name string }
	var found []stale
	for _, pkg := range pkgs {
		for _, f := range pkg.Syntax {
			tf := pkg.Fset.File(f.Pos())
			if tf == nil || made[filepath.Clean(tf.Name())] || !c.marked(f) {
				continue
			}
			if c.Keep != nil && c.Keep(pkg, tf.Name()) {
				continue
			}
			shown := tf.Name()
			if pkg.Module != nil && pkg.Module.Dir != "" {
				if rel, err := filepath.Rel(pkg.Module.Dir, shown); err == nil && inside(rel) {
					shown = rel
				}
			}
			found = append(found, stale{path: tf.Name(), name: shown})
		}
	}
	slices.SortFunc(found, func(a, b stale) int { return cmp.Compare(a.path, b.path) })

	staleErr := func(s stale) error { return c.warning(s.name) }
	return slices.Collect(opiter.Map(staleErr, slices.Values(found)))
}

// Dir returns a warning wrapping ErrStale for each Go file directly in dir
// of fsys holding a declaration marked by the generator that is not among
// produced, sorted by path. dir and the paths of produced are
// slash-separated and relative to the root of fsys. It serves generators
// that read no packages. Keep is not consulted.
//
// Every marked file of dir must come from the one run: files another run
// of the generator wrote there are reported.
func (c StaleCheck) Dir(fsys fs.FS, dir string, produced []File) ([]error, error) {
	made := map[string]bool{}
	for _, f := range produced {
		made[path.Clean(f.Path)] = true
	}

	entries, err := fs.ReadDir(fsys, dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("base: read %q: %w", dir, err)
	}
	var out []error
	for _, e := range entries {
		name := path.Join(dir, e.Name())
		if e.IsDir() || !strings.HasSuffix(name, ".go") || made[name] {
			continue
		}
		src, err := fs.ReadFile(fsys, name)
		if err != nil {
			return nil, fmt.Errorf("base: read %q: %w", name, err)
		}
		f, err := parser.ParseFile(
			token.NewFileSet(), name, src, parser.ParseComments|parser.SkipObjectResolution,
		)
		// A file that does not parse cannot be told to be generated, and is
		// for the compiler to report.
		if err != nil || !c.marked(f) {
			continue
		}
		out = append(out, c.warning(name))
	}
	return out, nil
}

func (c StaleCheck) warning(name string) error {
	return fmt.Errorf(
		"%w: %s was generated by %s but not produced by this run; delete it if no longer needed",
		ErrStale,
		name,
		c.Generator,
	)
}

// marked reports whether a declaration of f carries the marker of the
// generator.
func (c StaleCheck) marked(f *ast.File) bool {
	marked := func(cg *ast.CommentGroup) bool {
		gen, ok := c.Registry.Generated(cg)
		return ok && gen == c.Generator
	}
	markedSpec := func(spec ast.Spec) bool {
		switch s := spec.(type) {
		case *ast.TypeSpec:
			return marked(s.Doc)
		case *ast.ValueSpec:
			return marked(s.Doc)
		}
		return false
	}
	markedDecl := func(node ast.Decl) bool {
		switch d := node.(type) {
		case *ast.FuncDecl:
			return marked(d.Doc)
		case *ast.GenDecl:
			return marked(d.Doc) || opiter.ContainsFunc(markedSpec, slices.Values(d.Specs))
		}
		return false
	}
	return opiter.ContainsFunc(markedDecl, slices.Values(f.Decls))
}
