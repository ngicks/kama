func TestPrepareComposed(t *testing.T) {
	env, _, _ := driveEnv(t)

	parser := importdecl.NewParser(types.NewPackage("example.com/p", "p"))
	assert.NilError(t, parser.Require(
		importdecl.Import{Package: importdecl.Package{Path: "example.com/q", Name: "q"}},
		importdecl.Import{Package: importdecl.Package{Path: "fmt", Name: "fmt"}},
		importdecl.Import{Package: importdecl.Package{Path: "context", Name: "context"}},
	))
	imports, err := parser.ParseAst(nil)
	assert.NilError(t, err)

	files, err := gentest.Assemble(t, yielding([]base.Output{
		base.Composed{
			Path:            "d/p_linux.go",
			Params:          map[string]any{"k": "v"},
			BuildConstraint: "//go:build linux",
			Package:         "p",
			Imports:         imports,
			Parts: []base.Part{
				base.Text("// Section.\n"),
				base.Decl("// F is f.\nfunc F() {}"),
				base.Decl("var V = 1\n"),
			},
		},
	}), env.Registry, struct{}{})
	assert.NilError(t, err)
	assert.Equal(t, len(files), 1)
	assert.Equal(t, files[0].Path, "d/p_linux.go")
	assert.Equal(t, string(files[0].Content), `// Code generated by acme:drive. DO NOT EDIT.
// params:
//	k: "v"
// generated: 2026-11-04T10:12:33Z

//go:build linux

package p

import (
	"context"
	"fmt"

	"example.com/q"
)

// Section.

//kama:generated acme:drive
// F is f.
func F() {}

//kama:generated acme:drive
var V = 1
`)
}

// TestDriveMarkAfterFormat stages a stamped declaration: the formatter
// moves the mark to the end of the doc comment, where the registry finds
// it.
func TestDriveMarkAfterFormat(t *testing.T) {
	env, f, _ := driveEnv(t)

	g := yielding([]base.Output{base.Composed{
		Path:    "p.go",
		Package: "p",
		Parts:   []base.Part{base.Decl("// F is f.\nfunc F() {}")},
	}})
	assert.NilError(t, base.Drive(context.Background(), g, env, struct{}{}, base.Scope{}, f))

	src, err := fs.ReadFile(f.FS(), "p.go")
	assert.NilError(t, err)
	assert.Assert(
		t,
		strings.HasSuffix(
			string(src),
			"\n// F is f.\n//\n//kama:generated acme:drive\nfunc F() {}\n",
		),
		string(src),
	)

	file, err := parser.ParseFile(token.NewFileSet(), "p.go", src, parser.ParseComments)
	assert.NilError(t, err)

	gen, ok := env.Registry.Generated(file.Decls[0].(*ast.FuncDecl).Doc)
	assert.Assert(t, ok)
	assert.Equal(t, gen, driveId.String())
}

// TestDriveWholeEditsInPlace runs a generator appending a declaration to a
// file written by hand.
func TestDriveWholeEditsInPlace(t *testing.T) {
	ctx := context.Background()
	env, f, r := driveEnv(t)
	assert.NilError(t, f.Write(ctx, "hand.go", []byte("package p\n\ntype T int\n")))

	g := base.Generator[string]{
		Id: driveId,
		Generate: func(_ context.Context, env base.Env, name string) iter.Seq2[base.Output, error] {
			return func(yield func(base.Output, error) bool) {
				src, err := fs.ReadFile(env.Out, name)
				if err != nil {
					yield(nil, err)
					return
				}

				decl := base.Stamp(driveId, base.Decl("func (T) M() {}\n"))
				yield(base.Whole{Path: name, Content: slices.Concat(src, []byte("\n"), decl)}, nil)
			}
		},
	}
	assert.NilError(t, base.Drive(ctx, g, env, "hand.go", base.Scope{}, f))
	assert.DeepEqual(t, r.Messages, []string{"1 file written, 0 files unchanged"})

	src, err := fs.ReadFile(f.FS(), "hand.go")
	assert.NilError(t, err)
	assert.Equal(
		t,
		string(src),
		"package p\n\ntype T int\n\n//kama:generated acme:drive\nfunc (T) M() {}\n",
	)
}

// TestDriveVerbatimWholeKeepsBytes edits one literal of a hand-written file
// that is not gofmt-clean, and the file keeps every other byte.
func TestDriveVerbatimWholeKeepsBytes(t *testing.T) {
	ctx := context.Background()
	env, f, r := driveEnv(t)

	const hand = "package p\n\nconst   V   =  \"old\"   // keep\nvar x=[]int{1,2,  3}\n"
	assert.NilError(t, f.WriteFormatted("hand.go", []byte(hand)))

	g := base.Generator[string]{
		Id: driveId,
		Generate: func(_ context.Context, env base.Env, name string) iter.Seq2[base.Output, error] {
			return func(yield func(base.Output, error) bool) {
				src, err := fs.ReadFile(env.Out, name)
				if err != nil {
					yield(nil, err)
					return
				}

				edited := strings.Replace(string(src), `"old"`, `"new"`, 1)
				yield(base.Whole{Path: name, Content: []byte(edited), Verbatim: true}, nil)
			}
		},
	}
	assert.NilError(
		t,
		base.Drive(ctx, g, env, "hand.go", base.Scope{Files: []string{"hand.go"}}, f),
	)
	assert.DeepEqual(t, r.Messages, []string{"1 file written, 0 files unchanged"})
	assert.Equal(t, len(r.Warnings), 0)

	src, err := fs.ReadFile(f.FS(), "hand.go")
	assert.NilError(t, err)
	assert.Equal(t, string(src), strings.Replace(hand, `"old"`, `"new"`, 1))
}

// TestDriveStale runs generators into two sibling directories of one
// output, and one of them again without a file and with none.
func TestDriveStale(t *testing.T) {
	ctx := context.Background()
	env, f, _ := driveEnv(t)

	decl := base.Decl("var V = 1")
	run := func(dir string, names ...string) *gentest.RecordReporter {
		t.Helper()

		outs := make([]base.Output, 0, len(names))
		for i, name := range names {
			outs = append(outs, base.Composed{
				Path:    dir + "/" + name,
				Package: "p",
				Parts: []base.Part{
					base.Decl(strings.Replace(string(decl), "V", "V"+strconv.Itoa(i), 1)),
				},
			})
		}

		r := &gentest.RecordReporter{}
		env := env
		env.Reporter = r
		env.Out = f.FS()
		assert.NilError(
			t,
			base.Drive(ctx, yielding(outs), env, struct{}{}, base.Scope{Dirs: []string{dir}}, f),
		)

		return r
	}

	assert.Equal(t, len(run("a", "x.go", "y.go").Warnings), 0)
	// A run into a sibling directory owns none of the files of a.
	assert.Equal(t, len(run("b", "x.go").Warnings), 0)

	r := run("a", "x.go")
	assert.Equal(t, len(r.Warnings), 1, "%v", r.Warnings)
	assert.ErrorIs(t, r.Warnings[0], base.ErrStale)
	assert.ErrorContains(t, r.Warnings[0], "a/y.go holds declarations generated by acme:drive")

	r = run("a")
	assert.Equal(t, len(r.Warnings), 2, "%v", r.Warnings)
	assert.ErrorContains(t, r.Warnings[0], "a/x.go holds declarations generated by acme:drive")
	assert.ErrorContains(t, r.Warnings[1], "a/y.go holds declarations generated by acme:drive")
}

// noInParam is the param of a proc whose step takes no in.
type noInParam struct {
	Name string
}

type noInParamPartial struct {
	Name *string `json:"name"`
}

func (p noInParamPartial) Merge(r noInParamPartial) noInParamPartial {
	if r.Name != nil {
		p.Name = r.Name
	}

	return p
}

func (p noInParamPartial) ToValue() noInParam { return noInParam{Name: *p.Name} }

// TestProcWithoutIn builds and runs a graph around a Proc whose step takes
// no in.
func TestProcWithoutIn(t *testing.T) {
	ctx := context.Background()
	root := t.TempDir()
	// copy_down checks that the staged files compile, which takes a module.
	assert.NilError(t, os.WriteFile(root+"/go.mod", []byte("module example.com/p\n"), 0o644))

	name := "a.go"

	proc := base.Proc[noInParamPartial, noInParam, base.None, string]{
		Generator: base.Generator[string]{
			Id: driveId,
			Generate: func(_ context.Context, _ base.Env, name string) iter.Seq2[base.Output, error] {
				return func(yield func(base.Output, error) bool) {
					yield(base.Composed{
						Path:    name,
						Package: "p",
						Parts:   []base.Part{base.Decl("var V = 1")},
					}, nil)
				}
			},
		},
		Default: func() noInParamPartial { return noInParamPartial{Name: &name} },
		Check: func(p noInParam) error {
			if !strings.HasSuffix(p.Name, ".go") {
				return errors.New("drive: name is no Go file")
			}

			return nil
		},
		Input: func(
			_ context.Context,
			p noInParam,
			_ base.None,
			_ *overlayfs.Fs,
		) (string, base.Scope, error) {
			return "gen/" + p.Name, base.Scope{Dirs: []string{"gen"}}, nil
		},
		Now: func() time.Time { return gentest.Now() },
	}
	assert.Equal(t, len(proc.InTypes()), 0)

	reg := workflow.NewRegistry()
	assert.NilError(t, reg.Register("overlayfs.open", procoverlayfs.NewOpenProc))
	assert.NilError(t, reg.Register("overlayfs.copy_down", procoverlayfs.NewCopyDownProc))
	assert.NilError(t, reg.Register(driveId.ProcKind(), func() workflow.Proc { return proc }))

	spec := func(param map[string]any) workflow.Spec {
		return workflow.Spec{
			Version: 1,
			Steps: map[string]workflow.Step{
				"root": {Proc: "overlayfs.open", Param: map[string]any{"root": root}},
				"gen":  {Proc: driveId.ProcKind(), Out: workflow.Names{"root"}, Param: param},
				"done": {
					Proc:  "overlayfs.copy_down",
					In:    workflow.Names{"root"},
					After: workflow.Names{"gen"},
				},
			},
		}
	}

	_, err := spec(map[string]any{"name": "a.txt"}).Build(ctx, reg)
	assert.ErrorContains(t, err, "drive: name is no Go file")

	g, err := spec(map[string]any{"name": "b.go"}).Build(ctx, reg)
	assert.NilError(t, err)
	assert.NilError(t, g.Run(ctx, workflow.ProgressControl{}))

	src, err := os.ReadFile(root + "/gen/b.go")
	assert.NilError(t, err)
	assert.Assert(
		t,
		strings.HasSuffix(string(src), "//kama:generated acme:drive\nvar V = 1\n"),
		string(src),
	)
}

// TestCoreImportsNoDst keeps the framework core free of dst, which it must
// not make a dependency of every generator: no package the core imports,
// directly or not, is one of dst. A helper using dst lives in a package of
// its own.
func TestCoreImportsNoDst(t *testing.T) {
	pkgs, err := packages.Load(
		&packages.Config{Mode: packages.NeedName | packages.NeedImports | packages.NeedDeps},
		".",
	)
	assert.NilError(t, err)
	assert.Equal(t, len(pkgs), 1)

	var dsts []string

	packages.Visit(pkgs, nil, func(p *packages.Package) {
		if strings.HasPrefix(p.PkgPath, "github.com/dave/dst") {
			dsts = append(dsts, p.PkgPath)
		}
	})

	assert.Assert(t, len(pkgs[0].Imports) > 0)
	assert.DeepEqual(t, dsts, []string(nil))
}

// TestDriveKeepsUnchanged drives a generator three times: a run changing
// nothing but the time of the run keeps every file byte for byte.
func TestDriveKeepsUnchanged(t *testing.T) {
	env, f, _ := driveEnv(t)

	read := func(name string) string {
		b, err := fs.ReadFile(f.FS(), name)
		assert.NilError(t, err)

		return string(b)
	}
	run := func(now time.Time, a string) []string {
		t.Helper()

		r := &gentest.RecordReporter{}
		env := env
		env.Reporter, env.Now = r, now

		g := yielding([]base.Output{
			base.Composed{
				Path:    "a.go",
				Params:  map[string]any{"mode": "x"},
				Package: "p",
				Parts:   []base.Part{base.Decl(a)},
			},
			base.Composed{
				Path:    "sub/b.go",
				Package: "p",
				Parts:   []base.Part{base.Decl("var B = 1")},
			},
		})
		assert.NilError(t, base.Drive(t.Context(), g, env, struct{}{}, base.Scope{}, f))

		return r.Messages
	}

	first := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
	assert.DeepEqual(t, run(first, "var A = 1"), []string{"2 files written, 0 files unchanged"})

	a, b := read("a.go"), read("sub/b.go")

	assert.DeepEqual(
		t,
		run(first.Add(time.Hour), "var A = 1"),
		[]string{"0 files written, 2 files unchanged"},
	)
	assert.Equal(t, read("a.go"), a)

	assert.DeepEqual(
		t,
		run(first.Add(time.Hour), "var A = 2"),
		[]string{"1 file written, 1 file unchanged"},
	)
	assert.Assert(t, strings.Contains(read("a.go"), "var A = 2"))
	assert.Assert(t, strings.Contains(read("a.go"), "generated: 2026-01-01T01:00:00Z"))
	assert.Equal(t, read("sub/b.go"), b)
}
