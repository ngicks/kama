var driveId = base.Id{Namespace: "acme", Name: "drive"}

func init() { base.MustRegister(driveId) }

// yielding returns a generator yielding outs and errs in order, outs first.
func yielding(outs []base.Output, errs ...error) base.Generator[struct{}] {
	return base.Generator[struct{}]{
		Id: driveId,
		Generate: func(context.Context, base.Env, struct{}) iter.Seq2[base.Output, error] {
			return func(yield func(base.Output, error) bool) {
				for _, o := range outs {
					if !yield(o, nil) {
						return
					}
				}

				for _, err := range errs {
					if !yield(nil, err) {
						return
					}
				}
			}
		},
	}
}

// driveEnv returns the env of a run writing into a new overlay.
func driveEnv(t *testing.T) (base.Env, *overlayfs.Fs, *gentest.RecordReporter) {
	t.Helper()

	f, err := overlayfs.New(t.TempDir())
	assert.NilError(t, err)
	t.Cleanup(func() { _ = f.Close() })

	reg := genmark.NewRegistry(base.ToolName)
	assert.NilError(t, reg.Register(driveId.String()))

	r := &gentest.RecordReporter{}

	return base.Env{Reporter: r, Now: gentest.Now(), Registry: reg, Out: f.FS()}, f, r
}

func overlaid(t *testing.T, f *overlayfs.Fs) []string {
	t.Helper()

	ov, err := f.Overlay()
	assert.NilError(t, err)

	var names []string
	for name := range ov {
		names = append(names, strings.TrimPrefix(name, f.Root()+string(os.PathSeparator)))
	}

	slices.Sort(names)

	return names
}

func TestDriveStagesNothingOnError(t *testing.T) {
	env, f, _ := driveEnv(t)
	errA, errB := errors.New("a"), errors.New("b")

	g := yielding(
		[]base.Output{
			base.Whole{Path: "a.txt", Content: []byte("a")},
			base.Whole{Path: "../out.txt", Content: []byte("out")},
			base.Composed{Path: "b.go", Package: "p"},
		},
		errA,
		errB,
	)

	err := base.Drive(context.Background(), g, env, struct{}{}, base.Scope{}, f)
	assert.ErrorIs(t, err, errA)
	assert.ErrorIs(t, err, errB)
	assert.ErrorContains(t, err, `acme:drive: invalid path "../out.txt"`)
	assert.DeepEqual(t, overlaid(t, f), []string(nil))
}

func TestDriveStagesNothingOnFormatError(t *testing.T) {
	env, f, _ := driveEnv(t)

	g := yielding([]base.Output{
		base.Composed{Path: "a.go", Package: "p", Parts: []base.Part{base.Decl("var A = 1")}},
		base.Composed{Path: "b.go", Package: "p", Parts: []base.Part{base.Decl("var B = ")}},
	})

	err := base.Drive(context.Background(), g, env, struct{}{}, base.Scope{}, f)
	assert.ErrorContains(t, err, `acme:drive: format "b.go"`)
	assert.DeepEqual(t, overlaid(t, f), []string(nil))
}

