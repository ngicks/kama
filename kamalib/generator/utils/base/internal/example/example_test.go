package example_test

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"gotest.tools/v3/assert"

	"github.com/ngicks/kama/kamalib/generator/utils/base"
	_ "github.com/ngicks/kama/kamalib/generator/utils/base/internal/example/foo"
	_ "github.com/ngicks/kama/kamalib/generator/utils/base/internal/example/greet"
	"github.com/ngicks/kama/kamalib/kamasimple"
	"github.com/ngicks/kama/kamalib/workflow"
)

// spec is the spec the doc of package base shows, run in a module of its
// own.
const spec = `version: 1
steps:
  root:
    proc: overlayfs.open
  load:
    proc: packages.load
    in: root
    param:
      patterns: [./a, ./b]
  greet:
    proc: acme.greet.generate
    out: root
    param:
      input: names.yaml
  foo:
    proc: acme.foo.generate
    in: load
    out: root
    param:
      method: Label
  final:
    proc: overlayfs.copy_down
    in: root
    after: [greet, foo]
`

// TestExample runs greet and foo through the spec, and runs it again
// after b drops its directive: the file foo generated in b is stale.
func TestExample(t *testing.T) {
	dir := t.TempDir()
	write := func(name, content string) {
		t.Helper()
		assert.NilError(t, os.MkdirAll(filepath.Dir(filepath.Join(dir, name)), 0o755))
		assert.NilError(t, os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644))
	}
	read := func(name string) string {
		t.Helper()

		b, err := os.ReadFile(filepath.Join(dir, name))
		assert.NilError(t, err)

		return string(b)
	}

	write("go.mod", "module example.com/fixture\n\ngo 1.25\n")
	write("names.yaml", "names: [Alice, Bob]\n")
	write(
		"a/a.go",
		"package a\n\n//acme:foo label=apple\ntype A struct{}\n\n//acme:foo\ntype Apricot int\n",
	)
	write("b/b.go", "package b\n\n//acme:foo\ntype B struct{}\n")
	write("kama.yaml", spec)

	run := func() []error {
		t.Helper()

		var warnings []error

		t.Chdir(dir)

		assert.NilError(t, kamasimple.Run(context.Background(), kamasimple.Options{
			Spec: "kama.yaml",
			Progress: workflow.ProgressControl{
				OnWarning: func(_ string, w error) { warnings = append(warnings, w) },
			},
		}))

		return warnings
	}

	assert.Equal(t, len(run()), 0)

	greet := read("greet/zz_gen.greet.acme_greet.go")
	assert.Assert(
		t,
		strings.HasPrefix(greet, "// Code generated by acme:greet. DO NOT EDIT.\n"),
		greet,
	)
	assert.Assert(
		t,
		strings.Contains(greet, "// GreetAlice greets Alice.\n//\n//kama:generated acme:greet\n"+
			"func GreetAlice() string { return fmt.Sprintf(\"hello, %s\", \"Alice\") }\n"),
		greet,
	)
	assert.Equal(t, read("greet/names.txt"), "Alice\nBob\n")

	a := read("a/zz_gen.foo.acme_foo.go")
	assert.Assert(t, strings.Contains(a, "func (A) Label() string { return \"apple\" }"), a)
	assert.Assert(t, strings.Contains(a, "func (Apricot) Label() string { return \"apricot\" }"), a)
	assert.Assert(t, strings.Contains(read("b/zz_gen.foo.acme_foo.go"), "func (B) Label()"))

	write("b/b.go", "package b\n\ntype B struct{}\n")

	warnings := run()
	assert.Equal(t, len(warnings), 1, "%v", warnings)
	assert.ErrorIs(t, warnings[0], base.ErrStale)
	assert.ErrorContains(
		t,
		warnings[0],
		"b/zz_gen.foo.acme_foo.go holds declarations generated by acme:foo",
	)
}
