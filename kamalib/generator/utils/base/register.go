package base

import (
	"errors"
	"fmt"

	"github.com/ngicks/kama/kamalib/pkg/genmark"
)

// ToolName is the tool name of kama: the prefix of the directive comments
// the framework reads and writes for every generator, as in
// //kama:generated.
const ToolName = "kama"

// ErrInvalidId reports an Id that cannot name a generator.
var ErrInvalidId = errors.New("base: invalid generator id")

// defaultRegistry is unexported so that no package replaces the registry
// the init functions of the generators registered in.
var defaultRegistry = genmark.NewRegistry(ToolName)

// DefaultRegistry returns the Registry generators register their Ids in
// with MustRegister. A proc whose Registry is nil uses it.
func DefaultRegistry() *genmark.Registry { return defaultRegistry }

// Id identifies a generator. Namespace is kama for the generators of kama
// and the own name of a third party for its generators. Name is the
// generator within the namespace, such as partial. The pair names the
// directive of the generator, its option file key, its generated mark and
// its generated files.
type Id struct {
	Namespace string
	Name      string
}

// String returns the name the generated mark gives the generator, as in
// kama:partial.
func (id Id) String() string { return id.Namespace + ":" + id.Name }

// Marker returns the directive comment marking a declaration as emitted by
// the generator, as in //kama:generated kama:partial.
func (id Id) Marker() string { return genmark.Marker(ToolName, id.String()) }

// Directive returns the directive comment of the generator without args,
// as in //kama:partial.
func (id Id) Directive() string { return "//" + id.Namespace + ":" + id.Name }

// Naming returns the Naming of the files of the generator, named
// kama_partial for kama:partial.
func (id Id) Naming() Naming { return Naming{Name: id.Namespace + "_" + id.Name} }

// ProcKind returns the kind a workflow registry knows the proc of the
// generator by: partial.generate for kama:partial, and
// acme.partial.generate for acme:partial, so that a third party's
// generator never takes the kind of a generator of kama. It is
// ProcKindVerb with the verb generate.
func (id Id) ProcKind() string { return id.ProcKindVerb("generate") }

// ProcKindVerb returns the kind of the proc of the generator ending in
// verb instead of generate, as textmod.replace for kama:textmod. A
// generator whose proc does more than generate files names what it does.
func (id Id) ProcKindVerb(verb string) string {
	if id.Namespace == ToolName {
		return id.Name + "." + verb
	}

	return id.Namespace + "." + id.Name + "." + verb
}

// Validate returns an error wrapping ErrInvalidId for an Id that cannot
// name a generator. Each of Namespace and Name starts with an ASCII letter
// followed by ASCII letters, digits or underscores. The name of a file
// generated by the generator must carry no build constraint: the last
// underscore-separated element of the stem of Naming is neither test nor
// a known GOOS or GOARCH, as in acme_test, acme_linux or linux_amd64.
func (id Id) Validate() error {
	if err := id.validateWords(); err != nil {
		return err
	}

	if constrained("x" + id.Naming().Suffix() + ".go") {
		return fmt.Errorf(
			"%w: %q: the files it generates, named like x%s.go, would carry a build constraint",
			ErrInvalidId, id.String(), id.Naming().Suffix(),
		)
	}

	return nil
}

func isWord(s string) bool {
	if s == "" || !isLetter(s[0]) {
		return false
	}

	for i := range len(s) {
		if c := s[i]; !isLetter(c) && ('0' > c || c > '9') && c != '_' {
			return false
		}
	}

	return true
}

func isLetter(c byte) bool { return 'a' <= c && c <= 'z' || 'A' <= c && c <= 'Z' }

// validateWords checks the spelling of Namespace and Name alone.
func (id Id) validateWords() error {
	for _, part := range []string{id.Namespace, id.Name} {
		if !isWord(part) {
			return fmt.Errorf(
				"%w: %q: %q is not an ASCII letter followed by letters, digits or underscores",
				ErrInvalidId, id.String(), part,
			)
		}
	}

	return nil
}

// MustRegister checks the spelling of id and registers it in
// DefaultRegistry. A
// generator registers its Id from an init function: the framework drives
// only a registered generator, and the registry tells the generated marks
// of the registered generators from those of no generator, which the stale
// check and the conflict checks of the generators rely on. MustRegister
// panics on error, since an invalid or duplicate Id is a programming
// error.
func MustRegister(id Id) {
	// The build constraint check of Validate asks the go command for the
	// known platforms. An init function must not run a command, so only the
	// spelling is checked here. Prepare runs the whole of Validate.
	if err := id.validateWords(); err != nil {
		panic(err)
	}

	if err := defaultRegistry.Register(id.String()); err != nil {
		panic(err)
	}
}
