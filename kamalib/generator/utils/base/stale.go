package base

import (
	"errors"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"path"
	"slices"
	"strings"

	"github.com/ngicks/opiter"

	"github.com/ngicks/kama/kamalib/pkg/genmark"
)

// ErrStale reports a file of the scope of a run that carries the generated
// mark of a generator and that the run of the generator did not produce.
var ErrStale = errors.New("base: stale generated file")

// StaleCheck finds the files a generator wrote earlier and no longer
// produces.
type StaleCheck struct {
	// Registry tells the generator a marker names.
	Registry *genmark.Registry
	// Generator is the generator whose marked files the check finds.
	Generator Id
}

// Scope is where the stale check of a run looks for files carrying the
// generated mark of the generator. Paths are slash-separated and relative
// to the root of the output. The check cleans them as path.Clean does, so
// ./a.go names a.go, and rejects one that leaves the root.
type Scope struct {
	// Files are files the run is responsible for, such as the files of the
	// packages a run read.
	Files []string
	// Dirs are directories the run is responsible for. Every Go file
	// directly in one of them counts.
	Dirs []string
}

// InScope returns a warning wrapping ErrStale for each Go file of scope in
// fsys holding a declaration marked by the generator that is not among
// produced, sorted by path. The paths of produced are slash-separated and
// relative to the root of fsys. A file or a directory of scope that does
// not exist holds no stale file.
//
// The check works from the generated mark, so a file the generator edited
// in place in an earlier run counts as well as a file of its own. It looks
// at whole files: a stale declaration inside a file the run yields is left
// to the generator.
func (c StaleCheck) InScope(fsys fs.FS, scope Scope, produced []File) ([]error, error) {
	made := map[string]bool{}
	for _, f := range produced {
		made[path.Clean(f.Path)] = true
	}

	files, err := cleanPaths(scope.Files)
	if err != nil {
		return nil, err
	}

	dirs, err := cleanPaths(scope.Dirs)
	if err != nil {
		return nil, err
	}

	candidates := files

	for _, dir := range dirs {
		entries, err := fs.ReadDir(fsys, dir)
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}

		if err != nil {
			return nil, fmt.Errorf("base: read %q: %w", dir, err)
		}

		for _, e := range entries {
			if !e.IsDir() && strings.HasSuffix(e.Name(), ".go") {
				candidates = append(candidates, path.Join(dir, e.Name()))
			}
		}
	}

	var out []error

	for _, name := range slices.Compact(slices.Sorted(slices.Values(candidates))) {
		if made[path.Clean(name)] {
			continue
		}

		src, err := fs.ReadFile(fsys, name)
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}

		if err != nil {
			return nil, fmt.Errorf("base: read %q: %w", name, err)
		}

		f, err := parser.ParseFile(
			token.NewFileSet(), name, src, parser.ParseComments|parser.SkipObjectResolution,
		)
		// A file that does not parse cannot be told to be generated, and is
		// for the compiler to report.
		if err != nil || !c.marked(f) {
			continue
		}

		out = append(out, c.warning(name))
	}

	return out, nil
}

// cleanPaths returns paths cleaned, or an error for a path that is not
// slash-separated and relative to the root of the output.
func cleanPaths(paths []string) ([]string, error) {
	out := make([]string, 0, len(paths))

	for _, p := range paths {
		clean := path.Clean(p)
		if !fs.ValidPath(clean) {
			return nil, fmt.Errorf("base: scope: invalid path %q", p)
		}

		out = append(out, clean)
	}

	return out, nil
}

func (c StaleCheck) warning(name string) error {
	return fmt.Errorf(
		"%w: %s holds declarations generated by %s, and this run did not produce it; "+
			"delete them if they are no longer needed",
		ErrStale,
		name,
		c.Generator,
	)
}

// marked reports whether a declaration of f carries the marker of the
// generator.
func (c StaleCheck) marked(f *ast.File) bool {
	marked := func(cg *ast.CommentGroup) bool {
		gen, ok := c.Registry.Generated(cg)
		return ok && gen == c.Generator.String()
	}
	markedSpec := func(spec ast.Spec) bool {
		switch s := spec.(type) {
		case *ast.TypeSpec:
			return marked(s.Doc)
		case *ast.ValueSpec:
			return marked(s.Doc)
		}

		return false
	}
	markedDecl := func(node ast.Decl) bool {
		switch d := node.(type) {
		case *ast.FuncDecl:
			return marked(d.Doc)
		case *ast.GenDecl:
			return marked(d.Doc) || opiter.WrapSeq(slices.Values(d.Specs)).
				ContainsFunc(markedSpec)
		}

		return false
	}

	return opiter.WrapSeq(slices.Values(f.Decls)).
		ContainsFunc(markedDecl)
}
