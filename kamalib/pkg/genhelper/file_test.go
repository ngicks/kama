func TestPrintDstFile(t *testing.T) {
	const fooPath = "example.invalid/foo"

	pkg := types.NewPackage("example.invalid/p", "p")
	pkg.SetImports([]*types.Package{types.NewPackage(fooPath, "foo")})
	imports, err := importdecl.NewParser(pkg).ParseDst(nil)
	assert.NilError(t, err)

	foo, ok := imports.Ident(fooPath)
	assert.Assert(t, ok)

	decls, err := genhelper.ParseDecls([]byte("var x = " + foo + ".A\n"))
	assert.NilError(t, err)

	b, err := genhelper.PrintDstFile(
		"p", []string{"// Code generated by x. DO NOT EDIT."}, "//go:build linux", decls, imports,
	)
	assert.NilError(t, err)
	assert.Equal(t, string(b), `// Code generated by x. DO NOT EDIT.

//go:build linux

package p

import "example.invalid/foo"

var x = foo.A
`)

	decls, err = genhelper.ParseDecls([]byte("var x = 1\n"))
	assert.NilError(t, err)

	b, err = genhelper.PrintDstFile("p", nil, "", decls, nil)
	assert.NilError(t, err)
	assert.Equal(t, string(b), "package p\n\nvar x = 1\n")
}

func TestParseDecls(t *testing.T) {
	decls, err := genhelper.ParseDecls([]byte("var x = 1\nfunc f() {}\n"))
	assert.NilError(t, err)
	assert.Equal(t, len(decls), 2)

	for _, d := range decls {
		assert.Equal(t, d.Decorations().Before, dst.EmptyLine)
	}

	_, err = genhelper.ParseDecls([]byte("import \"fmt\"\n"))
	assert.ErrorIs(t, err, gofragment.ErrNotPartial)
}

func TestPrintFileHeader(t *testing.T) {
	for _, tc := range []struct {
		name   string
		header []string
		want   string
	}{
		{name: "no header", want: "package p\n\n"},
		{name: "empty sections only", header: []string{"", ""}, want: "package p\n\n"},
		{
			name:   "sections are separated by an empty line",
			header: []string{"// Code generated by x. DO NOT EDIT.", "//go:build linux"},
			want:   "// Code generated by x. DO NOT EDIT.\n\n//go:build linux\n\npackage p\n\n",
		},
		{
			name:   "plain text is commented",
			header: []string{"Code generated by x. DO NOT EDIT."},
			want:   "// Code generated by x. DO NOT EDIT.\n\npackage p\n\n",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			p := genhelper.NewBaseContext(genhelper.NewScope(), nil).Printer(nil)
			genhelper.PrintFileHeader(p, tc.header, "p")
			assert.Equal(t, string(p.Bytes()), tc.want)
		})
	}
}

func TestPrintComment(t *testing.T) {
	for _, tc := range []struct {
		name     string
		sections []string
		want     string
	}{
		{name: "no section"},
		{
			name:     "plain text spanning lines",
			sections: []string{"f does a thing.\n\nMore."},
			want:     "// f does a thing.\n//\n// More.\n",
		},
		{
			name:     "line comments stay",
			sections: []string{"// f does a thing.\n// More."},
			want:     "// f does a thing.\n// More.\n",
		},
		{
			name:     "block comment stays",
			sections: []string{"/*\nCopyright someone\n\n*/"},
			want:     "/*\nCopyright someone\n\n*/\n",
		},
		{
			name:     "trailing newline of a section adds no line",
			sections: []string{"plain\n", "// commented\n"},
			want:     "// plain\n\n// commented\n",
		},
		{
			name:     "each section is checked on its own",
			sections: []string{"// commented", "plain", "/* block */"},
			want:     "// commented\n\n// plain\n\n/* block */\n",
		},
		{
			name:     "empty section is skipped",
			sections: []string{"first", "", "second"},
			want:     "// first\n\n// second\n",
		},
		{
			name:     "unterminated block comment is plain text",
			sections: []string{"/* open"},
			want:     "// /* open\n",
		},
		{
			name:     "section mixing comment and text is plain text",
			sections: []string{"// commented\nplain"},
			want:     "// // commented\n// plain\n",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			p := genhelper.NewBaseContext(genhelper.NewScope(), nil).Printer(nil)
			genhelper.PrintComment(p, tc.sections)
			assert.Equal(t, string(p.Bytes()), tc.want)
		})
	}
}

func TestWrapComment(t *testing.T) {
	for _, tc := range []struct {
		name  string
		text  string
		width int
		want  string
	}{
		{name: "empty text"},
		{name: "fits on one line", text: "a b c", width: 8, want: "a b c"},
		{name: "prefix counts toward width", text: "aaaa bb", width: 8, want: "aaaa\nbb"},
		{name: "collapses spaces", text: " a \n b  c ", width: 20, want: "a b c"},
		{name: "long word takes its own line", text: "a abcdefgh b", width: 6, want: "a\nabcdefgh\nb"},
		{name: "paragraphs", text: "a b\n\nc", width: 20, want: "a b\n\nc"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, genhelper.WrapComment(tc.text, tc.width), tc.want)
		})
	}
}

func TestWrapFile(t *testing.T) {
	const (
		fooPath = "example.invalid/foo"
		barPath = "example.invalid/bar"
	)

	pkg := types.NewPackage("example.invalid/p", "p")
	pkg.SetImports([]*types.Package{
		types.NewPackage(fooPath, "foo"),
		types.NewPackage(barPath, "bar"),
	})
	// The map holds an import of an existing file and gains a missing one.
	f, err := decorator.Parse("package p\n\nimport f \"" + fooPath + "\"\n")
	assert.NilError(t, err)
	imports, err := importdecl.NewParser(pkg).ParseDst(f.Imports)
	assert.NilError(t, err)

	type ctx = genhelper.BaseContext

	steps := genhelper.Steps[ctx]{
		genhelper.Append(func(c ctx) (string, error) {
			foo, err := c.Package().Qual(fooPath, "A")
			if err != nil {
				return "", err
			}

			bar, err := c.Package().Qual(barPath, "B")
			if err != nil {
				return "", err
			}

			return "var _ = " + foo + " + " + bar + "\n", nil
		}),
		genhelper.WrapFile[ctx]([]string{"Code generated by x. DO NOT EDIT."}, "p"),
	}

	_, b, err := steps.Render(
		genhelper.NewBaseContext(
			genhelper.NewScope(),
			&genhelper.Package{Imports: imports, Path: "example.invalid/p"},
		),
		nil,
	)
	assert.NilError(t, err)
	assert.Equal(t, string(b), `// Code generated by x. DO NOT EDIT.

package p

import (
	"example.invalid/bar"
	f "example.invalid/foo"
)

var _ = f.A + bar.B
`)

	_, b, err = genhelper.WrapFile[ctx](nil, "p").Render(
		genhelper.NewBaseContext(genhelper.NewScope(), nil),
		[]byte("var x = 1\n"),
	)
	assert.NilError(t, err)
	assert.Equal(t, string(b), "package p\n\nvar x = 1\n")
}
